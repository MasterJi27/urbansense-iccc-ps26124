const UiCtx = createContext(null);

export function UiProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem(LANG_KEY) === "hi" ? "hi" : "en"; } catch { return "en"; }
  });
  const [monsoon, setMonsoon] = useState(() => readFlag(MONSOON_KEY, false));
  const [vru, setVru] = useState(() => readFlag(VRU_KEY, false));

  useEffect(() => {
    try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
    document.documentElement.lang = lang === "hi" ? "hi" : "en";
  }, [lang]);
  useEffect(() => { writeFlag(MONSOON_KEY, monsoon); }, [monsoon]);
  useEffect(() => { writeFlag(VRU_KEY, vru); }, [vru]);

  const value = useMemo(() => ({
    lang,
    setLang,
    toggleLang: () => setLang((l) => (l === "hi" ? "en" : "hi")),
    t: (k) => (dict[lang] && dict[lang][k]) || dict.en[k] || k,
    monsoon,
    setMonsoon,
    vru,
    setVru,
  }), [lang, monsoon, vru]);

  return <UiCtx.Provider value={value}>{children}</UiCtx.Provider>;
}

export function useUi() {
  const ctx = useContext(UiCtx);
  if (!ctx) throw new Error("useUi requires UiProvider");
  return ctx;
}
